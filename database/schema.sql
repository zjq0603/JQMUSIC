CREATE DATABASE IF NOT EXISTS jqmusic CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE jqmusic;

CREATE TABLE IF NOT EXISTS music_song (
  id VARCHAR(100) PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  artist_id VARCHAR(100), artist_name VARCHAR(255),
  album_id VARCHAR(100), album_name VARCHAR(255),
  cover_url TEXT, audio_url TEXT,
  source_type ENUM('LOCAL','ONLINE') NOT NULL DEFAULT 'LOCAL',
  source_name VARCHAR(100) NOT NULL DEFAULT 'Navidrome', source_platform_id VARCHAR(255),
  format VARCHAR(20), bitrate INT, duration INT,
  license_type VARCHAR(100), license_url TEXT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_song_title (title), INDEX idx_song_artist (artist_name)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS music_artist (
  id VARCHAR(100) PRIMARY KEY, name VARCHAR(255) NOT NULL, cover_url TEXT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS music_album (
  id VARCHAR(100) PRIMARY KEY, name VARCHAR(255) NOT NULL, artist_id VARCHAR(100), artist_name VARCHAR(255), cover_url TEXT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS music_playlist (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS music_playlist_song (
  playlist_id BIGINT UNSIGNED NOT NULL, song_id VARCHAR(100) NOT NULL, position INT NOT NULL DEFAULT 0,
  added_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (playlist_id, song_id), FOREIGN KEY (playlist_id) REFERENCES music_playlist(id) ON DELETE CASCADE,
  INDEX idx_playlist_order (playlist_id, position)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS music_favorite (
  song_id VARCHAR(100) PRIMARY KEY, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS music_play_history (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, song_id VARCHAR(100) NOT NULL, played_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_history_recent (played_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS music_source (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, source_type ENUM('LOCAL','ONLINE') NOT NULL,
  base_url TEXT, enabled BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS music_lyrics (
  song_id VARCHAR(100) PRIMARY KEY, lyrics MEDIUMTEXT, source VARCHAR(100), updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
